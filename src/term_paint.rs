/// The largest row or column number the encoding can spell, plus one. See [`ROWCOLUMN_DIACRITICS`].
pub const MAX_CELLS: usize = ROWCOLUMN_DIACRITICS.len();

/// The diacritic that spells `n`, or `None` when `n` is past the end of the table.
///
/// Returning an option rather than clamping is deliberate: a clamped row number draws the wrong
/// slice of the picture and looks like a rendering bug, where a refusal looks like what it is.
fn diacritic(n: usize) -> Option<char> {
    ROWCOLUMN_DIACRITICS.get(n).copied()
}

/// The number a diacritic spells, or `None` if it is not one of them.
///
/// The inverse exists for the tests — a table this size is only trustworthy if the round trip is
/// checked over the whole of it — and for whatever later needs to read back a placeholder cell.
/// The table is sorted ascending by construction, which the tests also assert, so this is a binary
/// search rather than a scan.
fn diacritic_number(ch: char) -> Option<usize> {
    ROWCOLUMN_DIACRITICS.binary_search(&ch).ok()
}

/// The SGR sequence that carries an image id in a cell's foreground colour.
///
/// **The 256-colour form is preferred and that is a tmux decision, not an aesthetic one.** The id
/// lives in the foreground colour, and tmux only forwards a 24-bit colour unchanged when it believes
/// the terminal underneath has `RGB`/`Tc` — otherwise it quantises it to the nearest palette entry,
/// which does not corrupt a colour so much as it corrupts an *identifier*, and the placeholder then
/// names an image that does not exist. An id that fits in eight bits can be written as a palette
/// index, which tmux passes through by definition. kitty's own documented example does exactly this:
/// `\x1b[38;5;42m` for image id 42.
///
/// Above eight bits there is no choice but true colour, so the caller is expected to keep bru's ids
/// small (see [`IMAGE_ID_VIEW`]). The top byte of a 32-bit id never travels in the colour at all —
/// it is a third diacritic, see [`most_significant_byte_diacritic`].
fn foreground_for_id(id: u32) -> String {
    let low = id & 0x00ff_ffff;
    if low <= 0xff {
        return format!("\x1b[38;5;{low}m");
    }
    let (r, g, b) = ((low >> 16) & 0xff, (low >> 8) & 0xff, low & 0xff);
    format!("\x1b[38;2;{r};{g};{b}m")
}

/// The third diacritic that carries bits 24..32 of the image id, or `None` when they are zero.
///
/// Omitted when zero because that is both shorter and what the protocol defaults to, and because
/// bru has no reason to hand out ids that large.
fn most_significant_byte_diacritic(id: u32) -> Option<char> {
    let msb = (id >> 24) as usize;
    if msb == 0 { None } else { diacritic(msb) }
}

/// Two image ids, distinct and deliberately small.
///
/// Small, because eight bits keeps the id in a palette index and out of tmux's colour quantiser
/// (see [`foreground_for_id`]). Not *tiny*, because kitty's image ids are a namespace shared by
/// everything in that terminal instance — `kitten icat` and every other well-behaved client start
/// counting from the bottom — so bru sits high in the byte where a collision is least likely. There
/// is no way to reserve one; the protocol offers image *numbers* (`I=`) which the terminal answers
/// with an id it chose, and reading that answer is exactly what a presenter that cannot listen
/// must not do. This is a considered guess and is labelled as one.
pub const IMAGE_ID_VIEW: u32 = 0xbe;
/// The image the transport probe hands over, which is never displayed. Its own id so that failing
/// the probe cannot disturb either of the two real images.
pub const IMAGE_ID_PROBE: u32 = 0xbd;

/// Put one pixel in shared memory for the transport probe to offer the terminal.
///
/// `None` when this machine has no usable `/dev/shm` at all — in which case there is nothing to ask
/// about and [`Transport::Base64`] is the answer without a round trip.
pub(crate) fn shm_probe_publish() -> Option<String> {
    let name = format!("/bru-probe-{}", std::process::id());
    shm_publish(&name, &[0u8; 3]).ok().map(|()| name)
}

/// Put arbitrary bytes in shared memory under a caller's name, for the capability table.
pub(crate) fn shm_stash(name: &str, bytes: &[u8]) -> bool {
    shm_publish(name, bytes).is_ok()
}

/// Take the probe's object back. Harmless if the terminal already consumed it.
pub(crate) fn shm_probe_release(name: &str) {
    shm_unlink(name);
}

/// Ask the terminal whether it can read a frame out of shared memory — `a=q` transmits nothing and
/// displays nothing, it only answers.
///
/// **This exists because a frame does not answer.** Real frames carry `q=2`, which asks for silence,
/// so a terminal that cannot read `t=s` refuses every one of them and bru never hears about it: the
/// pane stays black at full speed. `Transport::Base64` used to be reachable only when `shm_publish`
/// failed *locally*, which is a different question from whether the thing drawing the screen can
/// open the object. Measured 2026-08-26 in zellij 0.46.0.
pub(crate) fn shm_query_escape(name: &str, in_tmux: bool) -> String {
    let escape = format!(
        "\x1b_Gi={IMAGE_ID_PROBE},a=q,t=s,f=24,s=1,v=1;{}\x1b\\",
        base64(name.as_bytes())
    );
    passthrough(&escape, in_tmux)
}

/// What the terminal answered: `Some(true)` for `OK`, `Some(false)` for a refusal such as
/// `ENOENT:...`, and `None` when it said nothing about this image at all.
///
/// **Silence is not a refusal.** A terminal that answers nothing has told us nothing, and the
/// transport that has been working since this frontend was written is the better guess than one
/// chosen from an absence.
pub(crate) fn shm_query_answer(bytes: &[u8]) -> Option<bool> {
    let mut at = 0;
    while let Some(start) = bytes[at..].windows(3).position(|w| w == b"\x1b_G") {
        let start = at + start + 3;
        let end = bytes[start..].windows(2).position(|w| w == b"\x1b\\")? + start;
        let body = &bytes[start..end];
        let split = body.iter().position(|&b| b == b';');
        if let Some(split) = split {
            let (keys, payload) = (&body[..split], &body[split + 1..]);
            if keys.windows(2).any(|w| w == b"i=")
                && String::from_utf8_lossy(keys).contains(&format!("i={IMAGE_ID_PROBE}"))
            {
                return Some(payload.starts_with(b"OK"));
            }
        }
        at = end;
    }
    None
}

/// The popup layer (a `<select>` dropdown), which composes over the view. Its own id so the two do
/// not replace each other.
pub const IMAGE_ID_POPUP: u32 = 0xbf;

/// Where a picture goes, in cells, and which image it is.
///
/// `row` and `col` are **1-based screen coordinates**, because that is what `CSI row;col H` takes
/// and this struct exists to be turned into that. `rows` and `cols` are the size of the placeholder
/// rectangle, which is also what the virtual placement is told (`r=`, `c=`) — kitty fits the image
/// into that rectangle preserving aspect ratio, so the two must agree or the picture is letterboxed
/// inside its own cells.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Placement {
    pub image_id: u32,
    /// The placement id (`p=`). **Fixed rather than left to the terminal**, so that re-transmitting
    /// the same image every frame replaces one virtual placement instead of accumulating one per
    /// frame. The placeholder cells do not name it — that would need the underline colour, which is
    /// one more thing to get through tmux for no gain when there is only ever one placement of an
    /// image, and the protocol says an unnamed placement id means "any virtual placement of this
    /// image".
    pub placement_id: u32,
    pub row: u16,
    pub col: u16,
    pub rows: u16,
    pub cols: u16,
}

impl Placement {
    /// A placement filling a rectangle of the screen, with ids that do not collide.
    pub fn new(image_id: u32, row: u16, col: u16, rows: u16, cols: u16) -> Placement {
        Placement { image_id, placement_id: 1, row, col, rows, cols }
    }

    /// Whether the geometry can be spelled at all. See [`ROWCOLUMN_DIACRITICS`].
    pub fn is_encodable(&self) -> bool {
        self.rows >= 1
            && self.cols >= 1
            && usize::from(self.rows) <= MAX_CELLS
            && usize::from(self.cols) <= MAX_CELLS
    }
}

/// How much of each placeholder cell is spelled out.
///
/// The protocol lets a cell inherit row, column and id byte from the cell to its left, so a run can
/// be written as one full cell followed by bare placeholders — a quarter of the bytes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Style {
    /// Every cell carries its own row and column. **The default, and the reason is the host
    /// application.** Inheritance is resolved by kitty against the cell to the *left in kitty's own
    /// screen*, so it is only sound while that neighbour is still there with its diacritics intact.
    /// tmux repaints damaged spans, not whole lines, and a span that begins in the middle of a run
    /// of bare placeholders would arrive with nothing to inherit from. The saving is bytes in a
    /// write that happens when the layout changes — not per frame — so there is nothing to buy with
    /// the risk.
    Explicit,
    /// One full cell per row and bare placeholders after it, exactly as kitty documents it. Offered
    /// because it is a quarter of the text and some hosts are not tmux; see the warning above.
    Compact,
}

/// One row of placeholder cells: the colour, the cells, and the foreground put back.
///
/// **No newline, ever, and no cursor movement inside the run.** A character written into the last
/// cell of the last line sets the deferred-wrap flag rather than scrolling — but a newline after it
/// scrolls the pane, and a pane that scrolls by one line takes the image with it.
fn placeholder_row(placement: &Placement, row: u16, style: Style) -> Option<String> {
    let row_mark = diacritic(usize::from(row))?;
    let msb = most_significant_byte_diacritic(placement.image_id);
    let mut text = foreground_for_id(placement.image_id);
    for col in 0..placement.cols {
        text.push(PLACEHOLDER);
        match style {
            Style::Explicit => {
                text.push(row_mark);
                text.push(diacritic(usize::from(col))?);
                if let Some(msb) = msb {
                    text.push(msb);
                }
            }
            // kitty's documented short form: the first cell of the line gives the row and lets the
            // column and the id byte default, everything after it inherits both.
            Style::Compact => {
                if col == 0 {
                    text.push(row_mark);
                    if let Some(msb) = msb {
                        text.push(msb);
                    }
                }
            }
        }
    }
    // Foreground only. A full `SGR 0` here would drop whatever the session had set for the text
    // around the picture, and this module does not own that.
    text.push_str("\x1b[39m");
    Some(text)
}

/// The whole placeholder rectangle, each row positioned with `CSI row;col H`.
///
/// **This is the part that must not be wrapped for passthrough.** It is text; tmux is meant to read
/// it, store it and repaint it. Everything in this module that begins `\x1b_G` goes around tmux and
/// everything here goes through it, and confusing the two is how the picture stops following the
/// pane again.
///
/// Returns `None` for a geometry the diacritics cannot spell, which is the same refusal
/// [`Placement::is_encodable`] reports in advance.
fn placeholder_block(placement: &Placement, style: Style) -> Option<String> {
    if !placement.is_encodable() {
        return None;
    }
    // Save and restore the cursor around the whole block, because the caller's is none of our
    // business: DECSC/DECRC, which tmux implements natively and which also carries the SGR state.
    let mut text = String::from("\x1b7");
    for row in 0..placement.rows {
        let line = placement.row.saturating_add(row);
        text.push_str(&format!("\x1b[{line};{}H", placement.col));
        text.push_str(&placeholder_row(placement, row, style)?);
    }
    text.push_str("\x1b8");
    Some(text)
}

/// Wrap a graphics escape so tmux hands it to the terminal underneath instead of eating it.
///
/// The rule is a `DCS tmux;` wrapper with **every `\x1b` in the payload doubled**, terminated with
/// `\x1b\\`. Without `allow-passthrough on` in tmux the wrapper is dropped and nothing at all is
/// drawn — which is indistinguishable from a terminal with no graphics support, so whoever calls
/// this is the one who has to say which it was.
///
/// `in_tmux` is a parameter and not a look at the environment, so this stays a pure function that
/// the tests can drive both ways in one process.
fn passthrough(payload: &str, in_tmux: bool) -> String {
    if !in_tmux {
        return payload.to_string();
    }
    let mut wrapped = String::with_capacity(payload.len() + payload.len() / 8 + 16);
    wrapped.push_str("\x1bPtmux;");
    for ch in payload.chars() {
        if ch == '\x1b' {
            wrapped.push('\x1b');
        }
        wrapped.push(ch);
    }
    wrapped.push_str("\x1b\\");
    wrapped
}

/// The control keys every transmission in this module shares.
///
/// **`q=2` is not an optimisation and it is not optional here.** kitty's levels are 0 (answer), 1
/// (errors only) and 2 (silence). A presenter runs on the UI thread and cannot stop to read a
/// reply — and a reply nobody reads does not evaporate. Measured 2026-08-25: the spike sent frames
/// without `q`, never read the `OK`s, and tmux delivered the backlog **as keystrokes** to whichever
/// pane had focus, typing `Gi=1;OKGi=1;OK…` into a shell two panes away. Whoever cannot read the
/// answer does not get to ask the question. kitty's own documentation for Unicode placeholders says
/// the same thing for its own reason: a response would confuse the host application.
/// How the terminal is told *where* the picture goes.
///
/// **Two mechanisms, because one of them is not universal.** Unicode placeholders were chosen for
/// this module because they take the cursor out of the question entirely — the cells are text the
/// host repaints by itself, which is the whole reason a picture survives a tmux redraw. But a
/// placeholder is only a picture if the thing drawing the screen implements them, and a host that
/// does not will *accept every frame and show none of it*.
///
/// Measured 2026-08-26, in zellij 0.46.0: `--term-probe` reported 206 fps over shared memory with
/// **every frame acknowledged**, and the pane stayed black. The acknowledgement is `OK` for the
/// graphics command — it says the image was received and the shared memory was read, and says
/// nothing at all about anything being drawn. zellij intercepts graphics and re-emits them rather
/// than relaying the escape the way tmux does, and it does not implement placeholder cells.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Place {
    /// `U=1` plus a rectangle of placeholder cells. Survives a host repaint; needs the host to
    /// implement the placeholder protocol.
    Placeholders,
    /// `C=1` with the cursor moved to the rectangle's top-left cell first. Works anywhere the
    /// graphics protocol works at all, because it asks the terminal for nothing but a picture at
    /// the cursor.
    AtCursor,
}

/// Which mechanism this host can be drawn on.
pub fn place_for_host() -> Place {
    let set = |name: &str| std::env::var_os(name).is_some_and(|value| !value.is_empty());
    place_for(set("TMUX"), set("ZELLIJ"))
}

/// [`place_for_host`] as a function of its inputs, so it can be tested.
///
/// **tmux is answered first and cursor placement is not on the table there.** Under tmux the cursor
/// belongs to tmux: the graphics escape goes *around* it through DCS passthrough and arrives at a
/// terminal whose cursor is wherever tmux last left it, so "at the cursor" names a position nobody
/// agrees on. Placeholders exist for exactly that case.
///
/// Everything that is not a named exception keeps placeholders, which is the path this frontend has
/// been running on since it was written. This is a list of hosts known to need the other one, not a
/// guess about hosts in general.
fn place_for(in_tmux: bool, in_zellij: bool) -> Place {
    if in_tmux {
        return Place::Placeholders;
    }
    if in_zellij {
        return Place::AtCursor;
    }
    Place::Placeholders
}

/// Move the cursor to a placement's top-left cell, saving whatever the session had.
///
/// DECSC/DECRC rather than a second absolute move, because the cursor is the session's and this
/// module does not know where it was. See [`placeholder_block`], which brackets itself the same way
/// and for the same reason.
fn at_cursor_prologue(placement: &Placement) -> String {
    format!("\x1b7\x1b[{};{}H", placement.row, placement.col)
}

/// Put the cursor back. The other half of [`at_cursor_prologue`].
const AT_CURSOR_EPILOGUE: &str = "\x1b8";

fn common_keys(placement: &Placement, width: u32, height: u32, place: Place) -> String {
    // `C=1` and `U=1` sit in the same slot and are the whole difference between the two mechanisms:
    // one says "this image belongs to placeholder cells", the other "draw it here and do not move
    // the cursor". Everything after them is the same picture either way.
    let mode = match place {
        Place::Placeholders => "U=1",
        Place::AtCursor => "C=1",
    };
    format!(
        "a=T,{mode},q=2,i={},p={},f=24,s={width},v={height},c={},r={}",
        placement.image_id, placement.placement_id, placement.cols, placement.rows
    )
}

/// Transmit a frame by handing over the *name* of a shared memory object.
///
/// `t=s` means the payload is a POSIX shared memory name rather than pixels; kitty opens it, reads
/// it and unlinks it. The payload of a graphics escape is always base64, the name included. This is
/// the whole frame in about sixty bytes on the wire, which is why it is 9.7x base64 and why nothing
/// in this module compresses anything.
fn shm_escape(
    name: &str,
    placement: &Placement,
    width: u32,
    height: u32,
    place: Place,
) -> String {
    format!(
        "\x1b_G{},t=s;{}\x1b\\",
        common_keys(placement, width, height, place),
        base64(name.as_bytes())
    )
}

/// How many bytes of base64 go in one escape. The protocol's own limit is 4096.
const CHUNK: usize = 4096;

/// The fallback: the pixels themselves, base64, in 4 KB chunks.
///
/// **Kept because "the terminal supports graphics" and "this process can reach the terminal's
/// `/dev/shm`" are different claims** — an ssh session is the obvious case, and `shm_open` failing
/// is a fact discovered at runtime rather than configured. It is 8 fps on a full pane against 78,
/// so it is a way to still work and not a second way to work.
///
/// Only the first chunk carries the geometry; the rest carry `m` and nothing else, which is the
/// shape kitty documents. `q=2` is repeated on every chunk rather than trusted to stick to the
/// command, because the cost of the extra four bytes is four bytes and the cost of being wrong is
/// keystrokes in somebody else's pane.
fn base64_escapes(
    encoded: &str,
    placement: &Placement,
    width: u32,
    height: u32,
    place: Place,
) -> Vec<String> {
    if encoded.is_empty() {
        return Vec::new();
    }
    let mut escapes = Vec::with_capacity(encoded.len().div_ceil(CHUNK));
    let mut sent = 0;
    while sent < encoded.len() {
        let end = (sent + CHUNK).min(encoded.len());
        let more = i32::from(end < encoded.len());
        let keys = if sent == 0 {
            format!("{},m={more}", common_keys(placement, width, height, place))
        } else {
            format!("q=2,m={more}")
        };
        escapes.push(format!("\x1b_G{keys};{}\x1b\\", &encoded[sent..end]));
        sent = end;
    }
    escapes
}

/// Delete an image and free the pixels the terminal is holding for it.
///
/// `d=I` (capital) is "delete by id **and** release the data"; the lower-case form leaves the image
/// stored. Virtual placements can only be deleted by the `i`, `I`, `r`, `R`, `n` and `N` forms —
/// the ones that address an image rather than a place on the screen — because a virtual placement
/// has no place on the screen to address.
///
/// This does not erase the placeholder characters. They are text in the host application's screen
/// and the session is what owns that.
fn delete_escape(image_id: u32) -> String {
    format!("\x1b_Ga=d,d=I,i={image_id},q=2\x1b\\")
}

/// Base64, written here rather than pulled in: the whole of it is one table and three shifts, and a
/// dependency for that would be a dependency for that.
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] =
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b = [chunk[0], *chunk.get(1).unwrap_or(&0), *chunk.get(2).unwrap_or(&0)];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        out.push(ALPHABET[(n >> 18) as usize & 63] as char);
        out.push(ALPHABET[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 { ALPHABET[(n >> 6) as usize & 63] as char } else { '=' });
        out.push(if chunk.len() > 2 { ALPHABET[n as usize & 63] as char } else { '=' });
    }
    out
}

/// How many whole cells a picture of this many pixels covers.
///
/// The cell size is the pane's pixels divided by its cells — there is no escape that reports it
/// directly, and `TIOCGWINSZ` under tmux reports no pixels at all, which is why the pane's numbers
/// arrive from two different places and are passed in here rather than looked up.
///
/// Rounding is **down**, so the placement never claims a cell it cannot fill. The remainder is up to
/// a cell of unpainted pane at the right and bottom edges, which is a thin strip of background; the
/// alternative is a placement one cell too tall, which pushes the pane into scrolling.
fn cells_for(width: u32, height: u32, cell_width: u32, cell_height: u32) -> Option<(u16, u16)> {
    if cell_width == 0 || cell_height == 0 {
        return None;
    }
    let cols = u16::try_from(width / cell_width).ok()?;
    let rows = u16::try_from(height / cell_height).ok()?;
    if rows == 0 || cols == 0 { None } else { Some((rows, cols)) }
}

// --- damage ------------------------------------------------------------------------------------

/// A rectangle of pixels, in the frame's own coordinates. CEF's `on_paint` hands over a list of
/// these; this is the same thing without a dependency on CEF, so the arithmetic below can be tested
/// without a browser.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Rect {
    pub x: i32,
    pub y: i32,
    pub width: i32,
    pub height: i32,
}

/// The one rectangle that covers every dirty rectangle CEF reported, clipped to the frame.
///
/// `None` means nothing changed — which is the only use of damage this module actually makes, and
/// it is worth having on its own: a frame that CEF re-delivers unchanged costs a 4 MB copy into
/// `/dev/shm` and a texture upload for no visible difference.
///
/// ## Why the region is not transmitted, only measured
///
/// The obvious next step — send just the changed pixels — is **not available for a plain image**.
/// Checked against kitty's control-data reference on 2026-08-25: `x`, `y`, `w` and `h` are listed
/// under *keys for image display* and under *keys for animation frame loading*, and under neither
/// heading do they mean "patch the stored pixels of image `i`". For display they select which part
/// of an already-stored image to show; the only way to overwrite a sub-rectangle of stored pixels is
/// the animation path (`a=f` with `x`, `y` and `X=1` for a plain overwrite), which brings frame
/// numbers, inter-frame gaps and an animation state machine along with it. The task description this
/// module was written from assumed `a=t` could do it. It cannot.
///
/// And the reason not to reach for the animation path anyway is the measurement: with `t=s` a full
/// 990x1350 frame is a `memcpy` plus a sixty-byte escape and lands 78 times a second, confirmed.
/// Partial updates would trade that for per-region shared memory objects and a state machine, to
/// save a copy that is not what limits anything. If the transport ever *does* become the limit — a
/// much larger pane, or a terminal without shared memory where every frame is 5 MB of base64 — this
/// is the function that already knows how much of the frame is worth sending, and the second half is
/// then worth writing. Until then it decides whether to send at all.
fn damage_bounds(rects: &[Rect], width: u32, height: u32) -> Option<Rect> {
    let (frame_width, frame_height) = (i32::try_from(width).ok()?, i32::try_from(height).ok()?);
    let mut bounds: Option<(i32, i32, i32, i32)> = None;
    for rect in rects {
        // Clip first. A dirty rectangle that reaches past the frame is not a reason to compute a
        // bounding box that does the same.
        let left = rect.x.max(0);
        let top = rect.y.max(0);
        let right = rect.x.saturating_add(rect.width).min(frame_width);
        let bottom = rect.y.saturating_add(rect.height).min(frame_height);
        if right <= left || bottom <= top {
            continue;
        }
        bounds = Some(match bounds {
            None => (left, top, right, bottom),
            Some((l, t, r, b)) => (l.min(left), t.min(top), r.max(right), b.max(bottom)),
        });
    }
    let (left, top, right, bottom) = bounds?;
    Some(Rect { x: left, y: top, width: right - left, height: bottom - top })
}

// --- shared memory -----------------------------------------------------------------------------

/// How many handed-over shared memory objects are kept before their names are taken back.
///
/// **Not one, and the difference is a race.** kitty unlinks an object once it has read it, so the
/// tidy thing is to unlink the previous frame's when the next one is sent. But `shm_unlink` at the
/// moment kitty has not opened it yet turns that frame into an `ENOENT` and a dropped picture, and
/// at 78 fps the next frame is 13 ms away. Holding three generations gives the terminal about 38 ms
/// of grace and costs three frames of `/dev/shm` — 12 MB at a full pane, against a default
/// `/dev/shm` of half of RAM. Unlinking a name that is already gone fails harmlessly, which is why
/// the tidy-up is unconditional and unchecked.
const RETAINED_FRAMES: usize = 3;

/// Put `bytes` in a fresh POSIX shared memory object under `name`.
///
/// The object is created with `O_EXCL`, so this either makes a new one or fails; it never writes
/// into somebody else's. Everything it opens it closes, on every path, including the failing ones —
/// a leaked descriptor per frame is a file descriptor limit reached in under a minute.
fn shm_publish(name: &str, bytes: &[u8]) -> std::io::Result<()> {
    let c_name = std::ffi::CString::new(name)
        .map_err(|_| std::io::Error::new(std::io::ErrorKind::InvalidInput, "NUL in a shm name"))?;
    // SAFETY: `c_name` is a valid NUL-terminated string that outlives the call, and the flags are
    // the create-or-fail pair, so no existing object can be opened by accident.
    let fd = unsafe {
        libc::shm_open(c_name.as_ptr(), libc::O_CREAT | libc::O_EXCL | libc::O_RDWR, 0o600)
    };
    if fd < 0 {
        return Err(std::io::Error::last_os_error());
    }
    // From here on every exit closes the descriptor, and every *failing* exit also unlinks the
    // object — a name left behind after a failure is megabytes nobody will ever collect.
    let fail = |error: std::io::Error| -> std::io::Result<()> {
        // SAFETY: `fd` came from the `shm_open` above and is closed exactly once, on this path or
        // the successful one; the name is this process's own.
        unsafe {
            libc::close(fd);
            libc::shm_unlink(c_name.as_ptr());
        }
        Err(error)
    };
    let length = match libc::off_t::try_from(bytes.len()) {
        Ok(length) => length,
        Err(_) => {
            return fail(std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "a frame too large to size a shared memory object with",
            ));
        }
    };
    // SAFETY: `fd` is a shared memory object this function just created and owns exclusively.
    if unsafe { libc::ftruncate(fd, length) } != 0 {
        return fail(std::io::Error::last_os_error());
    }
    // SAFETY: the object was just sized to `bytes.len()`, so a mapping of that length lies within
    // it; `MAP_SHARED` is what makes the pixels visible to the terminal that opens the same name.
    let mapped = unsafe {
        libc::mmap(
            std::ptr::null_mut(),
            bytes.len(),
            libc::PROT_READ | libc::PROT_WRITE,
            libc::MAP_SHARED,
            fd,
            0,
        )
    };
    if mapped == libc::MAP_FAILED {
        return fail(std::io::Error::last_os_error());
    }
    // SAFETY: `mapped` is a writable mapping of exactly `bytes.len()` bytes, and the two regions
    // cannot overlap — one is a file mapping the kernel just handed out, the other this process's
    // own heap. The unmap that follows uses the same pointer and the same length.
    unsafe {
        std::ptr::copy_nonoverlapping(bytes.as_ptr(), mapped.cast::<u8>(), bytes.len());
        libc::munmap(mapped, bytes.len());
        libc::close(fd);
    }
    Ok(())
}

/// Take back a shared memory name the terminal did not.
///
/// Unchecked on purpose: the expected outcome is `ENOENT`, because kitty unlinks what it reads, and
/// the whole point of calling this is the case where it did not.
fn shm_unlink(name: &str) {
    if let Ok(c_name) = std::ffi::CString::new(name) {
        // SAFETY: the name is one this process created, and unlinking a name that is already gone
        // is a harmless failure rather than undefined behaviour.
        unsafe { libc::shm_unlink(c_name.as_ptr()) };
    }
}

// --- the presenter -----------------------------------------------------------------------------

/// How the pixels travel.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Transport {
    /// A name in `/dev/shm`. 78 fps at a full pane, through tmux, measured.
    SharedMemory,
    /// The pixels down the pty. 8 fps at the same size, measured. See [`base64_escapes`].
    Base64,
}

/// Everything one browser surface needs to keep appearing in the pane.
///
/// The division of labour, because it is not obvious from the outside: the **pixels** are re-sent
/// every frame and the **placeholder text** is not. Placeholders are text the host application owns
/// and repaints by itself — that is the entire reason they are used — so they are written when the
/// geometry changes and when somebody says the screen was clobbered, and never per frame. A frame is
/// one `memcpy` and one short escape.
pub struct Painter {
    placement: Placement,
    style: Style,
    in_tmux: bool,
    place: Place,
    transport: Transport,
    /// The geometry the placeholder cells on the screen were written for, or `None` when there are
    /// none — after a clear, a resize, or a caller saying the host repainted over them.
    placed: Option<Placement>,
    sequence: u64,
    /// Shared memory names handed over and not yet taken back. See [`RETAINED_FRAMES`].
    handed_over: VecDeque<String>,
}

impl Painter {
    pub fn new(
        placement: Placement,
        in_tmux: bool,
        place: Place,
        transport: Transport,
    ) -> Painter {
        Painter {
            placement,
            style: Style::Explicit,
            in_tmux,
            place,
            transport,
            placed: None,
            sequence: 0,
            handed_over: VecDeque::new(),
        }
    }

    /// Which transport frames are travelling by at the moment — the one asked for until shared
    /// memory fails once, and [`Transport::Base64`] from then on. See [`Painter::paint`].
    pub fn transport(&self) -> Transport {
        self.transport
    }

    /// Say where the picture goes. Re-writes the placeholder cells on the next paint.
    pub fn set_placement(&mut self, placement: Placement) {
        if placement != self.placement {
            self.placement = placement;
            self.placed = None;
        }
    }

    /// Say that the host application drew over the placeholder cells, so they must be written again.
    ///
    /// **The one thing the presenter cannot notice for itself.** tmux repaints its own screen, so it
    /// keeps the placeholders alive without being asked — but a full-screen clear, an alternate
    /// screen switch or another program's output erases them like any other text, and from the
    /// inside that is indistinguishable from nothing having happened. Whoever owns the screen knows.
    pub fn invalidate_placement(&mut self) {
        self.placed = None;
    }

    /// One frame: the pixels, and the placeholder cells if they are not already on the screen.
    ///
    /// `rgb` is `width * height * 3` bytes, because the transmission says `f=24`. Anything shorter
    /// is refused rather than padded — the length is the only thing standing between a wrong number
    /// and a picture made of whatever was next in memory.
    ///
    /// **The pixels go first and the cells second.** Either order converges, but this one never
    /// shows a placeholder for an image that does not exist yet.
    ///
    /// This does not switch synchronised output (mode 2026) on and off around itself. The session
    /// owns the screen and does that; a presenter that emitted its own would fight whatever else is
    /// drawing in the same frame.
    pub fn paint(
        &mut self,
        out: &mut impl Write,
        rgb: &[u8],
        width: u32,
        height: u32,
    ) -> std::io::Result<()> {
        let expected = (width as usize)
            .checked_mul(height as usize)
            .and_then(|pixels| pixels.checked_mul(3))
            .ok_or_else(|| {
                std::io::Error::new(std::io::ErrorKind::InvalidInput, "impossible frame size")
            })?;
        if rgb.len() < expected {
            return Err(std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "the frame is shorter than the size it would be transmitted as",
            ));
        }
        let rgb = &rgb[..expected];

        // **The cursor move and the picture are one write, not two.** Between the move and the
        // escape there is a cursor sitting somewhere the session did not put it, and anything else
        // that draws in that gap draws in the wrong place. Bracketed with DECSC/DECRC so the
        // session's cursor comes back untouched.
        if self.place == Place::AtCursor {
            out.write_all(at_cursor_prologue(&self.placement).as_bytes())?;
        }
        if self.transport == Transport::SharedMemory
            && !self.send_shared_memory(out, rgb, width, height)?
        {
            // Shared memory is not a configuration, it is a thing that either worked or did not —
            // no `/dev/shm` at all, a full one, a sandbox. Falling back once and staying fallen back
            // beats discovering it again for every frame.
            self.transport = Transport::Base64;
        }
        if self.transport == Transport::Base64 {
            for escape in base64_escapes(&base64(rgb), &self.placement, width, height, self.place)
            {
                out.write_all(passthrough(&escape, self.in_tmux).as_bytes())?;
            }
        }
        if self.place == Place::AtCursor {
            out.write_all(AT_CURSOR_EPILOGUE.as_bytes())?;
        }

        // Placeholder cells are the other mechanism's half of the job; at the cursor there is
        // nothing to write and nothing that can be clobbered, because the picture is not standing
        // in for any text.
        if self.place == Place::Placeholders && self.placed != Some(self.placement) {
            match placeholder_block(&self.placement, self.style) {
                Some(block) => {
                    // Text, so **not** wrapped for passthrough: tmux is meant to read this.
                    out.write_all(block.as_bytes())?;
                    self.placed = Some(self.placement);
                }
                None => {
                    return Err(std::io::Error::new(
                        std::io::ErrorKind::InvalidInput,
                        "a placement larger than the diacritics can spell",
                    ));
                }
            }
        }
        out.flush()
    }

    /// `Ok(false)` when shared memory itself was unavailable, which is the caller's cue to fall
    /// back; a write error to the terminal is a real error and comes back as one.
    fn send_shared_memory(
        &mut self,
        out: &mut impl Write,
        rgb: &[u8],
        width: u32,
        height: u32,
    ) -> std::io::Result<bool> {
        self.sequence = self.sequence.wrapping_add(1);
        // The name has to be unique for as long as the object is: the pid keeps it out of another
        // bru's way, the counter out of the previous frames' — see `RETAINED_FRAMES`.
        let name = format!("/bru-{}-{}", std::process::id(), self.sequence);
        if shm_publish(&name, rgb).is_err() {
            return Ok(false);
        }
        let escape = shm_escape(&name, &self.placement, width, height, self.place);
        let result = out.write_all(passthrough(&escape, self.in_tmux).as_bytes());
        self.handed_over.push_back(name);
        while self.handed_over.len() > RETAINED_FRAMES {
            if let Some(old) = self.handed_over.pop_front() {
                shm_unlink(&old);
            }
        }
        result?;
        Ok(true)
    }

    /// Give the image back to the terminal and forget the cells.
    ///
    /// The placeholder characters themselves are not erased here — they are text in the host
    /// application's screen, and erasing text is the session's job. What this does is release the
    /// pixels kitty is storing, so that a browser that has stopped is not also a picture the
    /// terminal is still holding.
    pub fn clear(&mut self, out: &mut impl Write) -> std::io::Result<()> {
        let escape = delete_escape(self.placement.image_id);
        out.write_all(passthrough(&escape, self.in_tmux).as_bytes())?;
        self.placed = None;
        out.flush()
    }
}

impl Drop for Painter {
    /// Take back every name the terminal did not. Without this a browser that exits mid-frame
    /// leaves up to [`RETAINED_FRAMES`] frames — 12 MB at a full pane — in `/dev/shm` until reboot.
    fn drop(&mut self) {
        for name in self.handed_over.drain(..) {
            shm_unlink(&name);
        }
    }
}

