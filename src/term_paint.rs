    /// Every escape byte doubled, wrapped in the DCS, terminated. Getting this wrong does not fail
    /// loudly — tmux eats the sequence and nothing is drawn, which reads as a terminal with no
    /// graphics support.
    #[test]
    fn the_tmux_wrapper_doubles_every_escape() {
        let payload = "\x1b_Ga=T;AAAA\x1b\\";
        assert_eq!(passthrough(payload, false), payload, "outside tmux nothing is added");
        let wrapped = passthrough(payload, true);
        assert!(wrapped.starts_with("\x1bPtmux;\x1b\x1b_Ga=T;AAAA"));
        assert!(wrapped.ends_with("\x1b\x1b\\\x1b\\"));
        assert_eq!(
            wrapped.matches('\x1b').count(),
            payload.matches('\x1b').count() * 2 + 2,
            "the payload's escapes are doubled and the wrapper adds two of its own"
        );
    }

