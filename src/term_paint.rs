    /// A shared memory object written and read back, which is the one thing here that needs a
    /// kernel rather than a terminal.
    #[test]
    fn a_frame_survives_the_trip_through_dev_shm() {
        let name = format!("/bru-test-{}-{}", std::process::id(), line!());
        let pixels: Vec<u8> = (0..=255u8).cycle().take(4096).collect();
        if shm_publish(&name, &pixels).is_err() {
            // A machine with no shared memory is exactly the case `Transport::Base64` exists for,
            // and is not a reason for the test suite to fail.
            return;
        }
        let path = std::path::Path::new("/dev/shm").join(name.trim_start_matches('/'));
        let read = std::fs::read(&path).expect("the object this test just created");
        shm_unlink(&name);
        assert_eq!(read, pixels);
        assert!(!path.exists(), "and the name is taken back");
        // Creating it a second time under the same name must not silently reuse somebody's object.
        shm_publish(&name, &pixels).expect("a fresh name");
        assert!(shm_publish(&name, &pixels).is_err(), "O_EXCL, so the second one fails");
        shm_unlink(&name);
    }
