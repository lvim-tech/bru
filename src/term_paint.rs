//! C4: how one frame reaches the screen.
//!
//! Two problems, and they are not the same problem. **Getting the pixels there** is answered by
//! shared memory, and it is answered: measured 2026-08-25 in kitty 0.48.2 under tmux next-3.8, a
//! 990x1350 pane, `t=s` did 78 fps with every frame acknowledged against 8 fps for the same picture
//! as base64 down the pty — 9.7x, and the belief that a multiplexer takes shared memory away turned
//! out to be false, because tmux only forwards the escape and kitty is the one that opens the
//! object. **Putting them in the right place** is not answered by that at all, and this module
//! exists mostly for the second half.
//!
//! ## Why the picture used to land crooked
//!
//! A kitty graphics escape places the image at **kitty's** cursor. Under tmux the escape reaches
//! kitty through `DCS tmux;` passthrough, which goes *around* tmux's screen model rather than
//! through it — so kitty's cursor is wherever tmux's last repaint happened to leave it, and it is
//! not where tmux thinks the cursor is. Sending `\x1b[H` from inside the pane moves the cursor tmux
//! owns; the image still lands at the other one. Measured 2026-08-25 with the spike: six lines of
//! startup log above the frame put the frame six lines down and its bottom off the pane, and every
//! repaint of the pane moved it again. Clearing the screen first is a mitigation and not a fix — it
//! works right up until something else repaints.
//!
//! ## Unicode placeholders, which take the cursor out of the question
//!
//! kitty 0.28 added a second way (`U=1`) that splits transmission from placement:
//!
//! 1. The image is **transmitted** and given a *virtual* placement — a prototype with a size in
//!    cells and no position at all. Nothing is drawn.
//! 2. The image is **placed** by printing ordinary text: runs of U+10EEEE, one per cell, carrying
//!    the image id in the cell's foreground colour and the row and column in combining diacritics.
//!
//! Step 2 goes through the *normal text path*. tmux stores those characters in its own screen like
//! any others, moves them when it redraws, and re-emits them where it decides they belong — so the
//! image follows the text, and the position stops depending on a cursor bru does not own. That is
//! the whole argument for the extra machinery below: not speed, which shared memory already settled,
//! but that the frame is where it is supposed to be after the pane is repainted.
//!
//! ## What this module does not do
//!
//! It does not turn CEF's BGRA into the RGB the protocol is told about (`f=24`) — that is the
//! composer's, which also has the popup layer to blend in — and it does not switch synchronised
//! output (mode 2026) on and off around a frame; the session owns the screen and does that. This
//! module takes a finished RGB buffer and a rectangle of cells, and is responsible for exactly the
//! journey between them.

// **Nothing calls this module yet, and it is the whole module rather than a few items.** C4 is the
// presenter; the session (C3) that owns the screen and the composer (C5) that produces the frames
// are being written beside it, and until one of them is wired up every public item here is
// unreachable from `main`. Thirty `#[allow(dead_code)]` attributes, one per item, would say the same
// thing thirty times and would have to be taken off thirty times. This comes off in one line the day
// the first caller lands — and until then `cargo clippy --all-targets -- -D warnings` stays clean,
// which is the point.
#![allow(dead_code)]

